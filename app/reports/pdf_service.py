import logging
from weasyprint import HTML

logger = logging.getLogger(__name__)

def generate_pdf_from_html(html_content: str) -> bytes | None:
    """Generate a PDF from raw HTML string using WeasyPrint."""
    try:
        pdf_bytes = HTML(string=html_content).write_pdf()
        return pdf_bytes
    except Exception as exc:
        logger.exception("generate_pdf_from_html failed: %s", exc)
        return None

def generate_rfq_pdf(
    requisition,
    supplier_name: str,
    items: list,
    issuer_name: str = "Procurement Department",
    issued_at=None,
) -> bytes | None:
    """Generate Request for Quotation (RFQ) PDF with issuer info, date, and time in footer."""
    from datetime import datetime as _dt, timezone as _tz
    from zoneinfo import ZoneInfo
    
    if issued_at is None:
        issued_at = _dt.now(_tz.utc)
        
    try:
        dhaka_tz = ZoneInfo("Asia/Dhaka")
        dhaka_time = issued_at.astimezone(dhaka_tz) if issued_at.tzinfo else issued_at.replace(tzinfo=_tz.utc).astimezone(dhaka_tz)
        date_str = dhaka_time.strftime("%B %d, %Y")
        time_str = dhaka_time.strftime("%I:%M %p")
    except Exception:
        date_str = issued_at.strftime("%B %d, %Y")
        time_str = issued_at.strftime("%I:%M %p")
    
    rows_html = ""
    for idx, item in enumerate(items, 1):
        name = item.get("name", "")
        desc = item.get("description", "")
        qty = item.get("shortlisted_qty", item.get("qty", ""))
        desc_html = f"<br><small style='color:#555;'>{desc}</small>" if desc else ""
        rows_html += f"<tr><td style='text-align:center;'>{idx}</td><td><b>{name}</b>{desc_html}</td><td style='text-align:center;font-weight:600;'>{qty}</td></tr>"

    html_content = f"""
    <!DOCTYPE html><html>
    <head><meta charset="utf-8">
    <style>
    @page{{margin:40px;}}
    body{{font-family:'Noto Sans Bengali','SolaimanLipi','Helvetica Neue',Arial,sans-serif;color:#1a1a1a;line-height:1.5;}}
    .wrap{{padding:20px;}}
    h1{{font-size:22px;border-bottom:2px solid #1a1a1a;padding-bottom:8px;margin-bottom:16px;text-align:center;color:#0f172a;}}
    table.meta{{width:100%;font-size:13px;margin-bottom:24px;}}
    table.meta td{{padding:5px 0;}}
    table.items{{border-collapse:collapse;width:100%;font-size:13px;margin-top:12px;}}
    table.items th{{border:1px solid #cbd5e1;padding:8px 10px;background:#f1f5f9;font-size:12px;text-align:left;color:#334155;}}
    table.items td{{border:1px solid #cbd5e1;padding:8px 10px;}}
    .footer{{margin-top:36px;font-size:11px;color:#475569;text-align:center;border-top:1px solid #e2e8f0;padding-top:14px;}}
    .footer strong{{color:#0f172a;}}
    </style></head>
    <body><div class="wrap">
    <p style="text-align:right;font-size:12px;color:#64748b;margin-bottom:16px">Date: {date_str}</p>
    <h1>Request for Quotation (RFQ / Tender)</h1>
    <table class="meta">
    <tr><td width="15%"><b>To:</b></td><td>{supplier_name}</td></tr>
    <tr><td><b>Requisition:</b></td><td>{requisition.title}</td></tr>
    </table>
    
    <p style="font-size:13px;color:#334155;margin-bottom:16px;">
        Please provide your competitive quotation for the specific line items listed below. Submit your quotation via the secure link provided in your email invitation.
    </p>
    
    <table class="items">
    <thead><tr><th width="8%" style="text-align:center">#</th><th width="72%">Item Description</th><th width="20%" style="text-align:center">Requested Qty</th></tr></thead>
    <tbody>{rows_html}</tbody>
    </table>
    
    <div class="footer">
        <p>Issued by: <strong>{issuer_name}</strong> &nbsp;|&nbsp; Date: <strong>{date_str}</strong> &nbsp;|&nbsp; Time: <strong>{time_str} BST</strong></p>
        <p style="font-size:10px;color:#94a3b8;margin-top:4px;">This is an official Request for Quotation (Tender) generated by Wener Supplier Management Platform.</p>
    </div>
    </div></body></html>
    """
    return generate_pdf_from_html(html_content)
